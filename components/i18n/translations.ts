export function normalizeLocale(value: string | undefined | null): AppLocale {
  return value === "zh" ? "zh" : "en";
}

export function translateUiText(value: string, locale: AppLocale): string {
  if (locale === "en" || !/[A-Za-z]/.test(value)) return value;
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return value;
  const [, before, core, after] = match;
  const exact = ZH_TRANSLATIONS[core];
  if (exact) return `${before}${exact}${after}`;
  for (const [pattern, replacement] of DYNAMIC_TRANSLATIONS) {
    if (pattern.test(core)) return `${before}${core.replace(pattern, replacement)}${after}`;
  }
  return value;
}

export function hasTranslation(value: string): boolean {
  return translateUiText(value, "zh") !== value;
}
